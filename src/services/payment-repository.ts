/**
 * Payment ledger — append-only.
 *
 *   payments/{YYYY-MM-DD}/{uid}/{pushKey} -> StoredPayment
 *
 * Entries are never edited or deleted. A mistake is corrected by a REVERSAL:
 * a new entry with a negative amount, `reversalOf` naming the original and a
 * mandatory `reversalReason`. Security rules enforce create-only for everyone,
 * admins included.
 *
 * `totalPaid` on the batch is a CACHE, maintained by an atomic server-side
 * increment in the same multi-path update that writes the entry. The ledger is
 * the source of truth; where the two disagree, the sum of entries wins and the
 * cache is recalculated from it.
 *
 * WHY NOT UNDER THE BATCH: in RTDB a write permitted at an ancestor grants the
 * whole subtree, and admins may write the batch node — so nested payments could
 * be erased by a batch write with no create-only rule able to stop it. The day
 * bucket is also keyed by PAYMENT date, not sale date, so a payment taken today
 * against last month's invoice lands in today's drawer.
 */

import type { PaymentEntry, PaymentMethod, SalesBatch, StoredPayment } from '@/components/records/types';
import { dbService } from '@/services/db';
import { localDayKey } from '@/utils/date';
import { roundNaira } from '@/utils/money';

const PAYMENTS_ROOT = 'payments';

export interface PaymentActor {
  uid: string;
  name: string;
}

/* ------------------------------------------------------------------ *
 * Pure core — no I/O, so the risky parts are testable.
 * ------------------------------------------------------------------ */

export interface BuildPaymentInput {
  batch: Pick<SalesBatch, 'dbPath' | 'id' | 'receiptId'>;
  /** Naira. Rounded here; negative only for a reversal. */
  amount: number;
  method: PaymentMethod;
  actor: PaymentActor;
  /** Push key, generated by the caller so this stays pure. */
  key: string;
  note?: string;
  reversalOf?: string;
  reversalReason?: string;
  /** Injectable for tests. */
  now?: Date;
}

export interface PaymentWrite {
  dayKey: string;
  paymentPath: string;
  totalPaidPath: string;
  /**
   * Pointer index on the SALE: `sales/…/{saleId}/paymentRefs/{key}`.
   *
   * The ledger is bucketed by payment date, which makes Daily Cash a
   * single-day read but leaves "this sale's payments" a scan across every day.
   * This ref makes that lookup structural without moving the ledger.
   *
   * It is an INDEX, not a record. The entry under `payments/…` is the money;
   * this only says where to find it. If a ref is ever lost, it is rebuildable
   * from the ledger — see scripts/backfill-payment-refs.ts.
   */
  refPath: string;
  /** `{dayKey}/{uid}` — the ledger location, minus the shared key. */
  refValue: string;
  entry: StoredPayment;
  /** Whole naira; what `totalPaid` must move by. */
  delta: number;
}

/**
 * Build the atomic write for one payment.
 *
 * Returns BOTH paths that must move together. Applying only one of them leaves
 * the ledger and the cached total disagreeing permanently, which is why the
 * caller sends them in a single multi-path update rather than two writes.
 */
export function buildPaymentWrite(input: BuildPaymentInput): PaymentWrite {
  const now = input.now ?? new Date();
  const dayKey = localDayKey(now);
  const amount = roundNaira(input.amount);

  if (input.reversalOf && !input.reversalReason?.trim()) {
    throw new Error('A reversal must state a reason.');
  }
  if (!input.reversalOf && amount <= 0) {
    throw new Error('A payment must be greater than zero.');
  }

  const entry: StoredPayment = {
    amount,
    method: input.method,
    at: now.toISOString(),
    atMs: now.getTime(),
    byUid: input.actor.uid,
    byName: input.actor.name,
    receiptId: input.batch.receiptId ?? input.batch.id,
    batchPath: input.batch.dbPath,
    ...(input.note?.trim() ? { note: input.note.trim() } : {}),
    ...(input.reversalOf
      ? { reversalOf: input.reversalOf, reversalReason: input.reversalReason!.trim() }
      : {}),
  };

  // The ref reuses the entry's own key, so ref key === entry key and the two
  // can be reconciled by set comparison rather than by parsing values.
  const refValue = `${dayKey}/${input.actor.uid}`;

  return {
    dayKey,
    paymentPath: `${PAYMENTS_ROOT}/${dayKey}/${input.actor.uid}/${input.key}`,
    totalPaidPath: `${input.batch.dbPath}/totalPaid`,
    refPath: `${input.batch.dbPath}/paymentRefs/${input.key}`,
    refValue,
    entry,
    delta: amount,
  };
}

/** @internal Exported for unit tests. */
export function normalizePayment(
  raw: StoredPayment,
  id: string,
  dayKey: string,
  uid: string,
): PaymentEntry {
  return {
    id,
    dbPath: `${PAYMENTS_ROOT}/${dayKey}/${uid}/${id}`,
    dayKey,
    amount: roundNaira(raw.amount ?? 0),
    method: (raw.method ?? 'Cash') as PaymentMethod,
    at: raw.at ?? '',
    atMs: raw.atMs ?? 0,
    byUid: raw.byUid ?? uid,
    byName: raw.byName ?? 'Unknown',
    receiptId: raw.receiptId ?? '',
    batchPath: raw.batchPath ?? '',
    note: raw.note,
    reversalOf: raw.reversalOf,
    reversalReason: raw.reversalReason,
    isReversal: !!raw.reversalOf,
  };
}

/**
 * Parse the `payments` tree into a flat list, newest first.
 *
 * Tolerates a partial tree: a staff member can only read their own uid bucket,
 * so the shape they receive is `{ [day]: { [theirUid]: { … } } }`.
 *
 * @internal Exported for unit tests.
 */
export function parsePaymentsTree(root: any): PaymentEntry[] {
  if (!root || typeof root !== 'object') return [];
  const out: PaymentEntry[] = [];

  for (const [dayKey, byUid] of Object.entries(root)) {
    if (!byUid || typeof byUid !== 'object') continue;
    for (const [uid, entries] of Object.entries(byUid as Record<string, any>)) {
      if (!entries || typeof entries !== 'object') continue;
      for (const [id, raw] of Object.entries(entries as Record<string, any>)) {
        if (!raw || typeof raw !== 'object') continue;
        out.push(normalizePayment(raw as StoredPayment, id, dayKey, uid));
      }
    }
  }

  return out.sort((a, b) => b.atMs - a.atMs);
}

