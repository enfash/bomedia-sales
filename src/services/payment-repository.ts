/**
 * Subscribe to the payment ledger.
 *
 * Kept separate from `subscribeToBatches` so Records and the Board do not pay
 * to fetch payments they never render.
 */
/**
 * One sale's payments, via its `paymentRefs` index.
 *
 * Replaces a subscription to the WHOLE ledger that filtered client-side to find
 * one sale's entries. Payments accumulate faster than sales, so that read
 * degraded sooner than anything else in the app.
 *
 * Subscribes to the ref map only, then fetches each entry once. Entries are
 * immutable — create-only by rule, corrected by reversal rather than edit — so
 * there is nothing to watch on them. The ref map is the only thing that changes
 * when a payment is added, and adding one re-runs this.
 */
export function subscribeToPaymentsForSale(
  batchPath: string,
  callback: (payments: PaymentEntry[]) => void,
): () => void {
  let cancelled = false;

  const unsubscribe = dbService.subscribe<Record<string, string>>(
    `${batchPath}/paymentRefs`,
    async (refs) => {
      if (!refs) {
        if (!cancelled) callback([]);
        return;
      }

      const entries = await Promise.all(
        Object.entries(refs).map(async ([key, location]) => {
          const node = await dbService.getRecord<StoredPayment>(
            `${PAYMENTS_ROOT}/${location}/${key}`,
          );
          if (!node) return null;
          const [dayKey, uid] = location.split('/');
          return normalizePayment(node, key, dayKey, uid);
        }),
      );

      if (cancelled) return;
      callback(
        entries
          .filter((e): e is PaymentEntry => e !== null)
          .sort((a, b) => b.atMs - a.atMs),
      );
    },
  );

  return () => {
    cancelled = true;
    unsubscribe();
  };
}

/**
 * Subscribe to a WINDOW of days, inclusive.
 *
 * Scoping an integrity check necessarily weakens it: a discrepancy outside the
 * window is not seen. That is inherent to scoping, not a flaw in it — so
 * anything built on this must SAY what period it covers rather than implying
 * the whole ledger agrees. Silence outside the window is the failure mode the
 * check exists to prevent, only quieter.
 */
export function subscribeToPaymentsInRange(
  startDayKey: string,
  endDayKey: string,
  callback: (payments: PaymentEntry[]) => void,
): () => void {
  return dbService.subscribeToKeyRange(PAYMENTS_ROOT, startDayKey, endDayKey, (root) =>
    callback(parsePaymentsTree(root)),
  );
}

/** Subscribe to a single day — what the reconciliation view needs. */
export function subscribeToPaymentsForDay(
  dayKey: string,
  callback: (payments: PaymentEntry[]) => void,
): () => void {
  return dbService.subscribe(`${PAYMENTS_ROOT}/${dayKey}`, (byUid) =>
    callback(parsePaymentsTree(byUid ? { [dayKey]: byUid } : null)),
  );
}

/* ------------------------------------------------------------------ *
 * Writes
 * ------------------------------------------------------------------ */

export interface RecordPaymentInput {
  batch: Pick<SalesBatch, 'dbPath' | 'id' | 'receiptId'>;
  amount: number;
  method: PaymentMethod;
  actor: PaymentActor;
  note?: string;
}

/**
 * Record a payment against a sale.
 *
 * The entry and the `totalPaid` increment go in ONE atomic multi-path update.
 * Two sequential writes could leave the ledger and the cache disagreeing
 * forever if the second failed.
 *
 * The increment is applied server-side, so two devices taking payments on the
 * same invoice both land — unlike the read-modify-write this replaces, where
 * the second write silently erased the first.
 */
export async function recordPayment(input: RecordPaymentInput): Promise<string> {
  const dayKey = localDayKey(new Date());
  const key = dbService.newKey(`${PAYMENTS_ROOT}/${dayKey}/${input.actor.uid}`);

  const write = buildPaymentWrite({ ...input, key });

  await dbService.updateAtomic({
    [write.paymentPath]: write.entry,
    [write.totalPaidPath]: dbService.increment(write.delta),
    [write.refPath]: write.refValue,
  });

  return key;
}

/**
 * Reverse a payment. Admin-only, enforced by the security rules.
 *
 * Writes a NEW entry with the negated amount rather than touching the original.
 * The original stays in the ledger forever — that is what makes the history
 * auditable rather than merely current.
 */
export async function reversePayment(
  original: PaymentEntry,
  reason: string,
  actor: PaymentActor,
): Promise<string> {
  if (!reason.trim()) throw new Error('A reversal must state a reason.');
  if (original.isReversal) throw new Error('A reversal cannot itself be reversed.');

  const dayKey = localDayKey(new Date());
  const key = dbService.newKey(`${PAYMENTS_ROOT}/${dayKey}/${actor.uid}`);

  const write = buildPaymentWrite({
    batch: {
      dbPath: original.batchPath,
      id: original.receiptId,
      receiptId: original.receiptId,
    },
    amount: -original.amount,
    method: original.method,
    actor,
    key,
    reversalOf: original.id,
    reversalReason: reason,
  });

  await dbService.updateAtomic({
    [write.paymentPath]: write.entry,
    [write.totalPaidPath]: dbService.increment(write.delta),
    [write.refPath]: write.refValue,
  });

  return key;
}

/**
 * Reset a batch's cached `totalPaid` to the sum of its ledger entries.
 *
 * The ONLY place `totalPaid` is written without an increment, and it only ever
 * writes what the ledger already says. Admin-only in the UI; it cannot invent
 * money, since its input is the entries themselves.
 */
export async function recalculateTotalPaid(
  batch: Pick<SalesBatch, 'dbPath'>,
  paymentsForBatch: PaymentEntry[],
): Promise<number> {
  const sum = paymentsForBatch.reduce((total, p) => total + p.amount, 0);
  await dbService.updateRecord(batch.dbPath, { totalPaid: roundNaira(sum) });
  return roundNaira(sum);
}
